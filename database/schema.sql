-- Execute no SQL Editor do projeto Supabase novo.
-- O acesso público às tabelas fica revogado. Somente a função do Netlify
-- usa a chave de serviço guardada como variável privada no Netlify.

create extension if not exists pgcrypto;

create table if not exists public.svl_customers (
  id uuid primary key default gen_random_uuid(),
  nome text not null,
  documento text not null default '',
  telefone text not null,
  endereco text not null,
  email text not null unique,
  password_salt text not null,
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.svl_orders (
  id uuid primary key default gen_random_uuid(),
  number bigint generated by default as identity unique,
  client_id uuid not null references public.svl_customers(id),
  client_snapshot jsonb not null,
  items jsonb not null,
  total numeric(12,2) not null check (total >= 0),
  status text not null default 'novo'
    check (status in ('novo','confirmado','em_preparacao','enviado','entregue','cancelado')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists svl_orders_client_created_idx
  on public.svl_orders (client_id, created_at desc);

alter table public.svl_customers enable row level security;
alter table public.svl_orders enable row level security;

revoke all on table public.svl_customers from anon, authenticated;
revoke all on table public.svl_orders from anon, authenticated;
grant all on table public.svl_customers to service_role;
grant all on table public.svl_orders to service_role;
grant usage, select on all sequences in schema public to service_role;
